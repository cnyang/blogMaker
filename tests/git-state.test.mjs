import test from 'node:test';
import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { mkdtemp, mkdir, writeFile, rm, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { restoreGitState, persistGitState } from '../scripts/git-state.mjs';

test('state branch persists a partial journal separately and restores it in a fresh workspace', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'blogger-git-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const remote = join(dir, 'remote.git');
  const root = join(dir, 'workspace');
  const exec = promisify(execFile);
  const git = async (...args) => (await exec('git', args, { cwd: root, encoding: 'utf8' })).stdout.trim();
  await exec('git', ['init', '--bare', remote]);
  await mkdir(root);
  await git('init', '-b', 'main');
  await git('remote', 'add', 'origin', remote);
  const path = join(root, '.blogger/state.json');
  const snapshot = await restoreGitState(root, path);
  assert.equal(snapshot.parent, null);
  await mkdir(join(root, '.blogger'));
  const first = JSON.stringify({ version: 1, blogId: '123', posts: { a: { postId: '100', sourceHash: null } } }) + '\n';
  await writeFile(path, first);
  await persistGitState(root, path, snapshot);
  await rm(path);
  const restored = await restoreGitState(root, path);
  assert.equal(await readFile(path, 'utf8'), first);
  assert.deepEqual((await git('ls-tree', '--name-only', restored.parent)).split('\n'), ['posts.json']);
  await persistGitState(root, path, restored);
  assert.equal(await git('rev-parse', 'origin/blogger-state'), restored.parent);
  await writeFile(path, first.replace('null', '"' + 'a'.repeat(64) + '"'));
  await persistGitState(root, path, restored);
  const latest = await restoreGitState(root, path);
  assert.notEqual(latest.parent, restored.parent);
  assert.equal(await git('rev-parse', `${latest.parent}^`), restored.parent);
  assert.equal(await git('branch', '--show-current'), 'main');
});
